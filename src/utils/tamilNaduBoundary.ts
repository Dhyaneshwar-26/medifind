/**
 * Small enclave exclusions for Puducherry and Karaikal, which are union
 * territories surrounded by Tamil Nadu. These are deliberately conservative
 * rectangles/circles so a pharmacy inside those UTs is never accepted as TN.
 */
export const TAMIL_NADU_EXCLUSION_RINGS: LngLat[][] = [
  // Puducherry town and surrounding communes
  [[79.735, 11.855], [79.885, 11.855], [79.885, 12.065], [79.735, 12.065], [79.735, 11.855]],
  // Karaikal
  [[79.755, 10.825], [79.915, 10.825], [79.915, 11.015], [79.755, 11.015], [79.755, 10.825]],
];

export interface BoundaryCheckResult {
  inside: boolean;
  reason?: 'outside_tamil_nadu' | 'puducherry_or_karaikal' | 'invalid_coordinates';
}

export function isValidCoordinatePair(lat: number, lng: number): boolean {
  return (
    Number.isFinite(lat) &&
    Number.isFinite(lng) &&
    lat >= -90 &&
    lat <= 90 &&
    lng >= -180 &&
    lng <= 180
  );
}

/** Ray-casting point-in-polygon test. Ring may be open or closed. */
export function isPointInRing(lng: number, lat: number, ring: LngLat[]): boolean {
  if (!Array.isArray(ring) || ring.length < 3) return false;
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    const intersects =
      yi > lat !== yj > lat &&
      lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
    if (intersects) inside = !inside;
  }
  return inside;
}

export function checkTamilNaduBoundary(lat: number, lng: number): BoundaryCheckResult {
  if (!isValidCoordinatePair(lat, lng)) {
    return { inside: false, reason: 'invalid_coordinates' };
  }
  if (!isPointInRing(lng, lat, TAMIL_NADU_MAINLAND_RING)) {
    return { inside: false, reason: 'outside_tamil_nadu' };
  }
  for (const exclusion of TAMIL_NADU_EXCLUSION_RINGS) {
    if (isPointInRing(lng, lat, exclusion)) {
      return { inside: false, reason: 'puducherry_or_karaikal' };
    }
  }
  return { inside: true };
}
